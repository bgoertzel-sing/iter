import os
import time
import uuid
import re
import importlib.util
from pathlib import Path
import chromadb

DESCRIPTION = "Store a memory in the PeTTa chroma_db long-term memory. The memory will be retrievable via chroma_query. Valid provenance types: observed, inferred, model_estimated. Long text is automatically split into linked chunks (each independently retrievable; chroma_query reassembles the full note when it matches one)."


def _emb():
    p = Path(__file__).resolve().parent / "_singularity_embeddings.py"
    spec = importlib.util.spec_from_file_location("_singularity_embeddings", p)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def _dupe_regex(text):
    """Build a regex that matches the whitespace-normalized text exactly (whitespace-flexible)."""
    norm = " ".join((text or "").split())
    if not norm:
        return None
    tokens = norm.split(" ")
    return "^" + r"\s+".join(re.escape(t) for t in tokens) + "$"


def _find_duplicate(collection, text):
    """Check if a whitespace-normalized duplicate already exists. Returns its id or None."""
    regex = _dupe_regex(text)
    if not regex:
        return None
    res = collection.get(where_document={"$regex": regex}, limit=1)
    ids = res.get("ids", [])
    return ids[0] if ids else None


def run(text, provenance_type="observed"):
    """
    text: str - the text to remember/store in long-term memory
    provenance_type: str - one of: observed, inferred, model_estimated
      observed: directly witnessed (sensor data, messages received, tool outputs)
      inferred: derived via reasoning (NAL inference, logical deduction)
      model_estimated: generated by the LLM (guesses, summaries, predictions)
    Tag and defer: no truth value assigned at admission.
    returns: str - success or error message
    """
    valid_types = {"observed", "inferred", "model_estimated"}
    if provenance_type not in valid_types:
        return f"ERROR: provenance_type must be one of {valid_types}, got '{provenance_type}'"

    emb = _emb()
    db_path = str(Path.home() / "PeTTa" / "chroma_db")
    chroma_client = chromadb.PersistentClient(path=db_path)
    collection = chroma_client.get_or_create_collection(
        name="memories",
        embedding_function=None
    )

    # Duplicate guard: refuse to store whitespace-normalized duplicates (checked
    # against the full, unchunked text so a resubmitted long note is still caught).
    existing_id = _find_duplicate(collection, text)
    if existing_id:
        return f"REMEMBER-DUPLICATE: identical memory already stored as {existing_id}; not re-storing"

    chunks = emb.chunk_text(text)
    if not chunks:
        return "ERROR: empty text"

    ts = time.strftime("%Y-%m-%d %H:%M:%S")
    embeddings = emb.embed_texts(chunks)

    if len(chunks) == 1:
        mem_id = str(uuid.uuid4())
        collection.add(
            ids=[mem_id],
            embeddings=[embeddings[0]],
            documents=[chunks[0]],
            metadatas=[{"time": ts, "provenance_type": provenance_type}]
        )
        return f"REMEMBER-SUCCESS: stored at {ts} (provenance: {provenance_type}) as {mem_id}"

    group_id = emb.new_chunk_group_id()
    ids = [str(uuid.uuid4()) for _ in chunks]
    metadatas = [
        {
            "time": ts,
            "provenance_type": provenance_type,
            "chunk_group": group_id,
            "chunk_index": i,
            "chunk_count": len(chunks),
        }
        for i in range(len(chunks))
    ]
    collection.add(ids=ids, embeddings=embeddings, documents=chunks, metadatas=metadatas)
    return (
        f"REMEMBER-SUCCESS: text exceeded the embedding model's safe input size; "
        f"stored at {ts} (provenance: {provenance_type}) as {len(chunks)} linked chunks "
        f"under group {group_id}"
    )
